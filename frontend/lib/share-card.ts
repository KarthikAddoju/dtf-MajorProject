import { formatDateTime, truncateValue } from "@/lib/formatting"
import type { VerificationRecord } from "@/lib/types"

function escapeXml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&apos;")
}

function sanitizeFilename(value: string) {
  const normalized = value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")

  return normalized || "credential"
}

export function buildCredentialShareCaption(
  record: VerificationRecord,
  shareUrl: string
) {
  return [
    `Verified academic credential on DACS`,
    `${record.courseName} • ${record.instituteName}`,
    `Token #${record.tokenId}`,
    record.eduAmount !== null
      ? `${record.eduAmount.toLocaleString()} EDU rewarded`
      : "EDU reward unavailable",
    shareUrl,
  ].join("\n")
}

